# IPAddress module-level validation methods (regex-only, no array/pack methods)
puts IPAddress.valid?("192.168.1.1")
puts IPAddress.valid?("10.0.0.256")
puts IPAddress.valid?("2001:db8::1")
puts IPAddress.valid?("2002::DEAD::BEEF")
puts IPAddress.valid_ipv4?("172.16.10.1")
puts IPAddress.valid_ipv4?("172.16.10.256")
puts IPAddress.valid_ipv6?("2002::1")
puts IPAddress.valid_ipv6?("10.0.0.1")
puts IPAddress.valid_ipv6?("::1")
puts IPAddress.valid_ipv4?("0.0.0.0")
